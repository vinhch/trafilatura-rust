"""Generates src/pystr/decimal.rs: the Python decimal digit table behind `crate::pystr`.

Regenerate with (from the repository root, Git Bash or Linux; Docker on Windows and macOS):

    scripts/oracle.sh 'from parity.gen_decimal import main; main()' > src/pystr/decimal.rs

The table comes from the interpreter that runs this, so the header records its version.
"""

import sys
import unicodedata

MAX_CODE_POINT = 0x10FFFF
DIGITS = 10
PER_LINE = 6


def zeros() -> list[int]:
    """Sorted code points whose decimal value is 0, after checking that they describe every digit.

    Every decimal digit `c` must have `unicodedata.decimal(c) == c - z` for the greatest zero
    `z <= c`, and every run of digits must be exactly ten characters, so that the zeros alone
    determine `str.isdecimal` and `unicodedata.decimal`.
    """
    digits = [
        code_point
        for code_point in range(MAX_CODE_POINT + 1)
        if unicodedata.decimal(chr(code_point), None) is not None
    ]
    assert digits == [c for c in range(MAX_CODE_POINT + 1) if chr(c).isdecimal()]
    assert digits == [c for c in range(MAX_CODE_POINT + 1) if unicodedata.category(chr(c)) == "Nd"]
    starts = [c for c in digits if unicodedata.decimal(chr(c)) == 0]
    assert starts == sorted(starts)
    covered: list[int] = []
    for start in starts:
        run = range(start, start + DIGITS)
        assert all(unicodedata.decimal(chr(c), None) == c - start for c in run), hex(start)
        covered.extend(run)
    assert covered == digits
    return starts


def char_literal(code_point: int) -> str:
    return f"'{chr(92)}u{{{code_point:X}}}'"


def main() -> None:
    version = ".".join(map(str, sys.version_info[:3]))
    cells = [char_literal(start) for start in zeros()]
    lines = [", ".join(cells[i : i + PER_LINE]) + "," for i in range(0, len(cells), PER_LINE)]
    body = "\n".join(f"    {line}" for line in lines)
    out = [
        f"// @generated by tools/parity/parity/gen_decimal.py with Python {version}, Unicode {unicodedata.unidata_version}.",
        "// Do not edit. Regenerate from the repository root with:",
        "//   scripts/oracle.sh 'from parity.gen_decimal import main; main()' > src/pystr/decimal.rs",
        "",
        "/// The digit zero of every run of ten decimal digits (`unicodedata.decimal(z) == 0`), sorted. The",
        "/// run holds the ten consecutive code points from `z`, whose decimal values are 0 to 9.",
        f"#[rustfmt::skip]\npub(super) static ND_ZEROS: &[char] = &[\n{body}\n];",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
