"""Generates src/pystr/printable.rs and src/pystr/alpha.rs: the Python character tables behind `crate::pystr`.

Regenerate with (from the repository root, Git Bash or Linux; Docker on Windows and macOS):

    scripts/oracle.sh 'from parity.gen_printable import main; main()' > src/pystr/printable.rs
    scripts/oracle.sh 'from parity.gen_printable import alpha; alpha()' > src/pystr/alpha.rs

The tables come from the interpreter that runs this, so the header records its version.
"""

import re
import sys
import unicodedata

MAX_CODE_POINT = 0x10FFFF
SURROGATES = range(0xD800, 0xE000)
PER_LINE = 6


def ranges(predicate) -> list[tuple[int, int]]:
    """Sorted inclusive (start, end) runs of the code points that satisfy `predicate`."""
    runs: list[tuple[int, int]] = []
    for code_point in range(MAX_CODE_POINT + 1):
        if not predicate(chr(code_point)):
            continue
        if runs and runs[-1][1] == code_point - 1:
            runs[-1] = (runs[-1][0], code_point)
        else:
            runs.append((code_point, code_point))
    return runs


def _hex(value: int) -> str:
    return f"0x{value:X}"


def table(name: str, doc: str, runs: list[tuple[int, int]]) -> str:
    # Rust `char` cannot hold a surrogate, and none of the predicates holds for one.
    assert not any(start in SURROGATES or end in SURROGATES for start, end in runs), name
    cells = [f"({_hex(start)}, {_hex(end)})" for start, end in runs]
    lines = [", ".join(cells[i : i + PER_LINE]) + "," for i in range(0, len(cells), PER_LINE)]
    body = "\n".join(f"    {line}" for line in lines)
    return f"/// {doc}\n#[rustfmt::skip]\npub(super) const {name}: &[(u32, u32)] = &[\n{body}\n];\n"


def esc(code_point: int) -> str:
    return chr(92) + f"x{{{code_point:X}}}"


def class_body(runs: list[tuple[int, int]]) -> str:
    """The runs as the body of a regex character class, every code point as a braced hex escape."""
    return "".join(esc(start) if start == end else f"{esc(start)}-{esc(end)}" for start, end in runs)


def constant(name: str, doc: str, runs: list[tuple[int, int]]) -> str:
    return f'/// {doc}\npub(crate) const {name}: &str = r"{class_body(runs)}";\n'


def main() -> None:
    version = ".".join(map(str, sys.version_info[:3]))
    space = ranges(str.isspace)
    printable = ranges(str.isprintable)
    word = ranges(lambda c: re.match(r"\w", c) is not None)
    out = [
        f"// @generated by tools/parity/parity/gen_printable.py with Python {version}, Unicode {unicodedata.unidata_version}.",
        "// Do not edit. Regenerate from the repository root with:",
        "//   scripts/oracle.sh 'from parity.gen_printable import main; main()' > src/pystr/printable.rs",
        "// Sorted inclusive code point ranges, surrogates excluded (a Rust `char` cannot hold one).",
        "",
        table("SPACE", "Code points for which Python's `str.isspace()` (and the `re` whitespace class) is true.", space),
        table("PRINTABLE", "Code points for which Python's `str.isprintable()` is true.", printable),
        table("WORD", "Code points for which Python's `re` word class matches, in Unicode mode.", word),
        constant("PY_SPACE_CLASS", "`SPACE` as the body of a regex character class.", space),
        constant("PY_WORD_CLASS", "`WORD` as the body of a regex character class.", word),
    ]
    sys.stdout.write("\n".join(out))


def alpha() -> None:
    version = ".".join(map(str, sys.version_info[:3]))
    out = [
        f"// @generated by tools/parity/parity/gen_printable.py with Python {version}, Unicode {unicodedata.unidata_version}.",
        "// Do not edit. Regenerate from the repository root with:",
        "//   scripts/oracle.sh 'from parity.gen_printable import alpha; alpha()' > src/pystr/alpha.rs",
        "// Sorted inclusive code point ranges, surrogates excluded (a Rust `char` cannot hold one).",
        "",
        table("ALPHA", "Code points for which Python's `str.isalpha()` is true (categories Lm, Lt, Lu, Ll, Lo).", ranges(str.isalpha)),
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
