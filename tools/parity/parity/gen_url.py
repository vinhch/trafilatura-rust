def cases() -> None:
    import html

    out = header(
        "src/pyurl/cases.rs",
        "cases",
        "CPython's `html.unescape` and `urllib.parse` run on fixed inputs.",
    )
    out += [
        "/// Input and `html.unescape` of it.",
        "#[rustfmt::skip]",
        "pub(crate) const UNESCAPE_CASES: &[(&str, &str)] = &[",
        *[f"    ({rust_str(s)}, {rust_str(html.unescape(s))})," for s in UNESCAPE_INPUTS],
        "];",
        "",
        *composition_cases(),
    ]
    sys.stdout.write("\n".join(out))


def checknetloc_raises(netloc: str) -> bool:
    from urllib.parse import _checknetloc

    try:
        _checknetloc(netloc)
    except ValueError:
        return True
    return False


def composition_cases() -> list[str]:
    """Each breaker next to a letter and to the combining marks that compose with their neighbours."""
    neighbours = ["a", "́", "̸"]
    strings = [b + n for b in netloc_breakers() for n in neighbours] + [n + b for b in netloc_breakers() for n in neighbours]
    return [
        "/// A netloc and whether `urllib.parse._checknetloc` raises on it.",
        "#[rustfmt::skip]",
        "pub(crate) const NFKC_COMPOSITION_CASES: &[(&str, bool)] = &[",
        *[f"    ({rust_str(s)}, {str(checknetloc_raises(s)).lower()})," for s in strings],
        "];",
        "",
    ]
