"""Generates the files behind `crate::pyurl`: Python's `html.unescape` and `urllib.parse` tables and cases.

Regenerate with (from the repository root, Git Bash or Linux; Docker on Windows and macOS):

    scripts/oracle.sh 'from parity.gen_url import tables; tables()' > src/pyurl/tables.rs
    scripts/oracle.sh 'from parity.gen_url import cases; cases()' > src/pyurl/cases.rs

The tables come from the interpreter that runs this, so the header records its version. The expected
values of the cases come from the same interpreter (CPython's own `html` and `urllib.parse`).
"""

import sys
import unicodedata

from parity.gen_xpath_cases import rust_str

SURROGATES = range(0xD800, 0xE000)
MAX_CODE_POINT = 0x10FFFF
# The characters `urllib.parse._checknetloc` looks for after NFKC normalization.
NETLOC_DELIMITERS = "/?#@:"


def version() -> str:
    return f"Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}"


def header(path: str, call: str, summary: str) -> list[str]:
    return [
        f"// @generated by tools/parity/parity/gen_url.py with {version()}.",
        "// Do not edit. Regenerate from the repository root with:",
        f"//   scripts/oracle.sh 'from parity.gen_url import {call}; {call}()' > {path}",
        f"// {summary}",
        "",
    ]


def netloc_breakers() -> list[str]:
    """Non-ASCII code points whose NFKC form holds a netloc delimiter, sorted.

    ASCII is out: `_checknetloc` returns early on an ASCII netloc, and a lone ASCII delimiter
    normalizes to itself, so `/` never raises it.
    """
    return [
        chr(code_point)
        for code_point in range(0x80, MAX_CODE_POINT + 1)
        if code_point not in SURROGATES
        and any(d in unicodedata.normalize("NFKC", chr(code_point)) for d in NETLOC_DELIMITERS)
    ]


def tables() -> None:
    from html.entities import html5

    entities = sorted(html5.items(), key=lambda item: item[0].encode())
    breakers = netloc_breakers()
    out = header(
        "src/pyurl/tables.rs",
        "tables",
        "Python's HTML5 entity table (sorted by name, byte order) and the NFKC netloc breakers (sorted).",
    )
    out += [
        "/// `html.entities.html5`, sorted by name in byte order for `binary_search_by`.",
        "#[rustfmt::skip]",
        "pub(super) static HTML5_ENTITIES: &[(&str, &str)] = &[",
        *[f"    ({rust_str(name)}, {rust_str(value)})," for name, value in entities],
        "];",
        "",
        "/// Non-ASCII characters whose NFKC form contains one of `/?#@:`, sorted: the characters",
        "/// `urllib.parse._checknetloc` rejects.",
        "#[rustfmt::skip]",
        "pub(super) static NFKC_NETLOC_BREAKERS: &[char] = &[",
        *[f"    '\\u{{{ord(c):X}}}'," for c in breakers],
        "];",
        "",
    ]
    sys.stdout.write("\n".join(out))


