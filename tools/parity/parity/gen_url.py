def unescape_or_none(s: str) -> str | None:
    "`html.unescape(s)`, or None where CPython raises ValueError."
    import html

    try:
        return html.unescape(s)
    except ValueError:
        return None


def rust_option(text: str | None) -> str:
    return "None" if text is None else f"Some({rust_str(text)})"


