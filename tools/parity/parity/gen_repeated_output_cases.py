"""Generates tests/repeated_output_tests/cases.rs: upstream's `repeated_output_tests.py` re-derived in fast mode.

Regenerate with (from the repository root, Git Bash or Linux; Docker on Windows and macOS):

    scripts/oracle.sh 'from parity.gen_repeated_output_cases import main; main()' > tests/repeated_output_tests/cases.rs

Upstream runs that file with the slow default (`fast=False`), and the crate has fast mode only (D-1), so
its expectation sets do not carry over: a page the slow path keeps whole may repeat words (or come back
empty) on the fast path. The generator imports the file by path from the checkout at the pin (the tables,
`_page`, `_number`, `_assert_unique`, the expectation sets), runs every test with `fast=True` inside
`parity.generate.html5_parsers()` (D-2) and writes the fast-mode outcome:

    EMPTY                  the keys of `test_no_repeated_words` whose result is `None`
    KNOWN_DUPLICATES       the keys whose result repeats a word, with upstream's reason when upstream lists
                           the key too, else "fast mode"
    COMMENT_LIST_REPEATED  the (tag, class, config) triples of `test_short_article_comment_list_not_repeated`
                           whose result repeats a word

The three tests without a set (`test_over_pruned_page_not_repeated`, `test_inline_only_frame_kept`,
`test_frame_lead_text_kept`) run as upstream wrote them; one that fails in fast mode fails the generation,
naming the case, because it then needs a hand-written D-1 expectation. A result that is empty or loses
words without repeating one has no place in the sets and fails the generation too.

The counts and every key that differs from upstream's `EMPTY` and `KNOWN_DUPLICATES` go to stderr.
"""

import importlib.util
import itertools
import os
import sys
import types
from pathlib import Path

from parity.gen_xpath_cases import rust_str

COMMENT_LISTS = (("ol", "commentlist"), ("ul", "comment-list"))
COMMENT_CONFIGS = {"default": {}, "recall": {"favor_recall": True}, "precision": {"favor_precision": True}}

HEADER = """\
// @generated by tools/parity/parity/gen_repeated_output_cases.py. Do not edit. Regenerate from the repository root with:
//   scripts/oracle.sh 'from parity.gen_repeated_output_cases import main; main()' > tests/repeated_output_tests/cases.rs
// The expectation sets of upstream's repeated_output_tests, re-derived with fast=True.

/// (block, inline, short, wrapper, config) of a page of `test_no_repeated_words`.
pub type Key = (&'static str, &'static str, bool, &'static str, &'static str);
"""


def load_upstream():
    "The upstream test module with `pytest` stubbed (the oracle image has none) and `extract` forced to fast mode."
    pytest = types.ModuleType("pytest")
    pytest.mark = types.SimpleNamespace(parametrize=lambda *args, **kwargs: (lambda func: func))
    sys.modules.setdefault("pytest", pytest)
    path = Path(os.environ["TRAFILATURA_UPSTREAM"]) / "tests" / "repeated_output_tests.py"
    spec = importlib.util.spec_from_file_location("upstream_repeated_output_tests", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    extract = module.extract
    module.extract = lambda *args, **kwargs: extract(*args, **{**kwargs, "fast": True})
    return module


def outcome(module, result: str | None, expected_words: int | None = None) -> str:
    "`none`, `repeated`, `short` (unique words, but not `expected_words` of them) or `ok`."
    if not result:
        return "none"
    try:
        words = module._assert_unique(result)
    except module.RepeatedWordsError:
        return "repeated"
    return "short" if expected_words is not None and len(words) != expected_words else "ok"


def product_sets(module) -> tuple[list, dict]:
    empty, duplicates = [], {}
    for block, inline, short, wrapper, config in itertools.product(
        module.BLOCKS, module.INLINE, (False, True), module.WRAPPERS, module.CONFIGS
    ):
        key = (block, inline, short, wrapper, config)
        result = module.extract(module._page(block, inline, wrapper, short), **module.CONFIGS[config])
        kind = outcome(module, result)
        if kind == "none":
            empty.append(key)
        elif kind == "repeated":
            duplicates[key] = module.KNOWN_DUPLICATES.get(key, "fast mode")
    return empty, duplicates


def comment_list_repeated(module) -> list:
    repeated = []
    for (tag, cls), (name, config) in itertools.product(COMMENT_LISTS, COMMENT_CONFIGS.items()):
        replies = "".join("<li><p>" + "@ " * 25 + "</p></li>" for _ in range(8))
        body = f"<article><p>@ @ @ @ @ @ @ @ @ @.</p></article><{tag} class='{cls}'>{replies}</{tag}>"
        kind = outcome(module, module.extract(module._number(body), **config), body.count("@"))
        if kind == "repeated":
            repeated.append((tag, cls, name))
        elif kind != "ok":
            raise AssertionError(f"comment list {tag} {cls} {name}: result is {kind}, no set holds that")
    return repeated


def plain_tests(module) -> None:
    "The three tests without a set, run as upstream wrote them; a failure names the case."
    cases = [
        ("test_over_pruned_page_not_repeated", (block, wrapper, config))
        for config in ("markdown", "precision")
        for wrapper in ("nested", "article")
        for block in ("p_in_li", "blockquote_in_li", "table_in_li")
    ] + [
        ("test_inline_only_frame_kept", (frame, inline)) for frame in ("article", "main") for inline in ("a", "b", "code", "em")
    ] + [
        ("test_frame_lead_text_kept", (config, child))
        for config in module.CONFIGS
        for child in ("<br/>", "<p>@ @ @ @ @ @ @ @ @ @.</p>")
    ]
    failed = []
    for name, args in cases:
        try:
            getattr(module, name)(*args)
        except AssertionError as error:
            failed.append(f"{name}{args}: {type(error).__name__}({error})")
    if failed:
        raise AssertionError("upstream assertions that fail in fast mode, each needs a hand-written D-1 expectation:\n"
                             + "\n".join(failed))


def rust_key(key) -> str:
    block, inline, short, wrapper, config = key
    return f"({rust_str(block)}, {rust_str(inline)}, {str(short).lower()}, {rust_str(wrapper)}, {rust_str(config)})"


def main() -> None:
    from parity.generate import html5_parsers

    module = load_upstream()
    with html5_parsers():
        plain_tests(module)
        empty, duplicates = product_sets(module)
        repeated = comment_list_repeated(module)

    out = [HEADER, "#[rustfmt::skip]", "pub const EMPTY: &[Key] = &["]
    out += [f"    {rust_key(key)}," for key in empty]
    out += ["];", "", "/// A key and the reason: upstream's when it lists the key too, else `fast mode`.", "#[rustfmt::skip]",
            "pub const KNOWN_DUPLICATES: &[(Key, &str)] = &["]
    out += [f"    ({rust_key(key)}, {rust_str(reason)})," for key, reason in duplicates.items()]
    out += ["];", "", "/// (tag, class, config) of `test_short_article_comment_list_not_repeated` that repeat a word.", "#[rustfmt::skip]",
            "pub const COMMENT_LIST_REPEATED: &[(&str, &str, &str)] = &["]
    out += [f"    ({rust_str(tag)}, {rust_str(cls)}, {rust_str(name)})," for tag, cls, name in repeated]
    out += ["];", ""]
    sys.stdout.write("\n".join(out))

    total = len(module.BLOCKS) * len(module.INLINE) * 2 * len(module.WRAPPERS) * len(module.CONFIGS)
    print(f"{total} keys: {len(empty)} empty (upstream {len(module.EMPTY)}), {len(duplicates)} known duplicates "
          f"(upstream {len(module.KNOWN_DUPLICATES)}); {len(repeated)} of "
          f"{len(COMMENT_LISTS) * len(COMMENT_CONFIGS)} comment lists repeat", file=sys.stderr)
    differences = {
        "empty in fast mode, not upstream": sorted(set(empty) - module.EMPTY),
        "empty upstream, text in fast mode": sorted(module.EMPTY - set(empty)),
        "duplicate in fast mode, not upstream": sorted(set(duplicates) - set(module.KNOWN_DUPLICATES)),
        "duplicate upstream, not in fast mode": sorted(set(module.KNOWN_DUPLICATES) - set(duplicates)),
        "duplicate upstream, empty in fast mode": sorted(set(module.KNOWN_DUPLICATES) & set(empty)),
    }
    for label, keys in differences.items():
        print(f"{label}: {len(keys)}", file=sys.stderr)
        for key in keys:
            print(f"    {key}", file=sys.stderr)


if __name__ == "__main__":
    main()
