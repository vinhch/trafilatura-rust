"""Generates the encoding parity tables: what upstream's `detect_encoding` and `decode_file` return, with
charset_normalizer, for a synthetic byte set and for the non-UTF-8 corpus pages.

Regenerate with (from the repository root, Git Bash or Linux; Docker on Windows and macOS):

    scripts/oracle.sh 'from parity.gen_encoding_cases import synthetic; synthetic()' > src/utils/tests/encoding_cases.rs
    scripts/oracle.sh 'from parity.gen_encoding_cases import corpus; corpus()' > tests/parity/encoding_cases.rs

Every synthetic input is built here from fixed text, never read from the network. The corpus table holds
digests, not text: the pages are third-party content.
"""

import hashlib
import sys

from parity.gen_xpath_cases import rust_str

CHARSET_NORMALIZER_VERSION = "3.5.2"

ASCII_HTML = "<html><head><title>Test</title></head><body><p>Hello, world.</p></body></html>"
CHINESE = "高山云雾出好茶，这是一个用于测试编码检测的中文段落，包含若干常见的汉字和标点符号。" * 3
JAPANESE = "吾輩は猫である。名前はまだ無い。どこで生れたかとんと見当がつかぬ。何でも薄暗いじめじめした所でニャーニャー泣いていた事だけは記憶している。" * 2
KOREAN = "대한민국의 수도는 서울이며, 한강이 도시를 가로질러 흐른다. 이 문단은 인코딩 검출을 시험하기 위한 한국어 문장이다." * 2
RUSSIAN = "Съешь же ещё этих мягких французских булок, да выпей чаю. Это тестовая страница на русском языке для проверки определения кодировки. "
GERMAN = "Über den Wölkchen, größere Straßen: Müßiggang ist aller Laster Anfang, sagte der Bäcker."
FRENCH = "Le café, la crème brûlée et l’été à Zürich: ça va très bien. "
ENGLISH = "The quick brown fox jumps over the lazy dog. <p>Hello</p>\n"


def rust_bytes(data: bytes) -> str:
    "A Rust byte string literal: printable ASCII as is, the rest as `\\xNN`."
    body = "".join(
        chr(b) if 0x20 <= b <= 0x7E and chr(b) not in '"\\' else f"\\x{b:02x}" for b in data
    )
    return f'b"{body}"'


def check_environment() -> None:
    import charset_normalizer
    from trafilatura import utils

    assert charset_normalizer.__version__ == CHARSET_NORMALIZER_VERSION, charset_normalizer.__version__
    assert utils.cchardet_detect is None, "cchardet must stay absent: the crate has no counterpart"


def header(script_entry: str, target: str) -> None:
    import charset_normalizer

    print(
        f"// @generated by tools/parity/parity/gen_encoding_cases.py with Python {sys.version.split()[0]}, "
        f"charset_normalizer {charset_normalizer.__version__}."
    )
    print("// Do not edit. Regenerate from the repository root with:")
    print(f"//   scripts/oracle.sh 'from parity.gen_encoding_cases import {script_entry}; {script_entry}()' > {target}")


def sample_and_whole(data: bytes):
    "The matches upstream's `detect_encoding` tries first (head and tail of a long input) and the whole input's."
    from charset_normalizer import from_bytes

    return from_bytes(data[:5000] + data[-5000:]), from_bytes(data)


def fails_to_decode(data: bytes, guess: str) -> bool:
    try:
        data.decode(guess)
    except (LookupError, UnicodeDecodeError):
        return True
    return False


def retry_whole() -> bytes:
    "Over 10,000 bytes: French UTF-8 with stray bytes at both ends gives no match on head + tail, the whole input one."
    from charset_normalizer import from_bytes

    for middle in (8000, 10000, 12000, 15000, 20000, 60000):
        for strays in (1, 3):
            head = (FRENCH.encode() * 200)[: 5000 - strays] + b"\xe9" * strays
            tail = b"\xe9" * strays + (FRENCH.encode() * 200)[: 5000 - strays]
            data = head + (ENGLISH.encode() * (middle // 50))[:middle] + tail
            if not from_bytes(data[:5000] + data[-5000:]) and from_bytes(data):
                return data
    raise AssertionError("no retry_whole input found")


def undefined_byte_outside_sample() -> bytes:
    "Over 10,000 bytes: the first guess decodes the sample but not a byte past the first 5,000."
    for undefined, text in ((0x98, RUSSIAN), (0x81, GERMAN), (0x8D, GERMAN)):
        encoding = "cp1251" if text == RUSSIAN else "cp1252"
        body = (text * (13000 // len(text.encode(encoding)) + 1)).encode(encoding)
        middle = len(body) // 2
        data = body[:middle] + bytes([undefined]) + body[middle:]
        sample, whole = sample_and_whole(data)
        if len(data) > 10000 and sample and fails_to_decode(data, sample[0].encoding):
            return data
    raise AssertionError("no undefined_byte_outside_sample input found")


def replace_fallback() -> bytes:
    "French UTF-8 with truncated sequences: no guess decodes it, so `decode_file` replaces."
    data = (FRENCH.encode() * 30) + b"\xe9 \xe2\x82 \xf0\x9f\x98 \xc3 \xff\xfe " + (FRENCH.encode() * 30)
    from trafilatura.utils import detect_encoding

    assert all(fails_to_decode(data, guess) for guess in detect_encoding(data)), "a guess decodes it"
    return data


def synthetic_inputs() -> list[tuple[str, bytes]]:
    gb = "高山云雾出好茶".encode("gb18030")
    return [
        ("utf8", CHINESE.encode()),
        ("utf8_bom", b"\xef\xbb\xbf" + CHINESE.encode()),
        ("cp1252_short", GERMAN.encode("cp1252")),
        ("cp1251_page", f"<html><body><p>{RUSSIAN * 22}</p></body></html>".encode("cp1251")),
        ("latin_1_controls", "Caf\x85 au lait, na\xefve fa\xe7ade, \x85 ellipsis \x85 and more.".encode("latin-1")),
        ("gb18030", gb),
        ("gb18030_x1000", gb * 1000),
        ("shift_jis", JAPANESE.encode("shift_jis")),
        ("euc_kr", KOREAN.encode("euc_kr")),
        ("big5", CHINESE.encode("big5", errors="ignore")),
        ("koi8_r", RUSSIAN.encode("koi8_r") * 4),
        ("utf_16_bom", ASCII_HTML.encode("utf-16")),
        ("utf_16le_nobom", ASCII_HTML.encode("utf-16-le")),
        ("utf_16le_nobom_cjk", f"<html><body><p>{CHINESE}</p></body></html>".encode("utf-16-le")),
        ("utf_32_bom", ASCII_HTML.encode("utf-32")),
        ("tiny_1", b"\xe9"),
        ("tiny_2", b"\xe9\xe8"),
        ("tiny_3", b"a\xe9\xff"),
        ("mostly_utf8_stray", ("é" * 200).encode() + b"\xe9"),
        ("utf8_bom_stray", b"\xef\xbb\xbf" + (FRENCH.encode() * 5) + b"\xe9" + FRENCH.encode()),
        ("retry_whole", retry_whole()),
        ("undefined_byte_outside_sample", undefined_byte_outside_sample()),
        ("replace_fallback", replace_fallback()),
    ]


def synthetic() -> None:
    check_environment()
    from trafilatura.utils import decode_file, detect_encoding

    rows = []
    for name, data in synthetic_inputs():
        guesses = detect_encoding(data)
        decoded = decode_file(data)
        rows.append(
            f"    EncodingCase {{ name: {rust_str(name)}, input: {rust_bytes(data)}, "
            f"guesses: &[{', '.join(rust_str(g) for g in guesses)}], decoded: {rust_str(decoded)} }},"
        )
    header("synthetic", "src/utils/tests/encoding_cases.rs")
    print("// Each case holds trafilatura.utils.detect_encoding(input) and trafilatura.utils.decode_file(input).")
    print()
    print("/// One byte input and what upstream returns for it.")
    print("pub(super) struct EncodingCase {")
    print("    pub(super) name: &'static str,")
    print("    pub(super) input: &'static [u8],")
    print("    /// `detect_encoding(input)`: codec names in rank order.")
    print("    pub(super) guesses: &'static [&'static str],")
    print("    /// `decode_file(input)`.")
    print("    pub(super) decoded: &'static str,")
    print("}")
    print()
    print("#[rustfmt::skip]")
    print("pub(super) const ENCODING_CASES: &[EncodingCase] = &[")
    for row in rows:
        print(row)
    print("];")


def corpus() -> None:
    import os
    from pathlib import Path

    from parity import page_id
    from parity.generate import corpus as corpus_pages
    from parity.generate import valid_utf8
    from trafilatura.utils import decode_file, detect_encoding, handle_compressed_file

    check_environment()
    root = Path(os.environ["TRAFILATURA_UPSTREAM"])
    rows = []
    for path in corpus_pages(root):
        data = path.read_bytes()
        if valid_utf8(data):
            continue
        source = path.relative_to(root).as_posix()
        assert handle_compressed_file(data) == data, f"{source} is compressed: detect_encoding sees other bytes"
        guesses = detect_encoding(data)
        decoded = decode_file(data)
        digest = hashlib.blake2b(decoded.encode("utf-8"), digest_size=16).digest()
        rows.append(
            f"    CorpusEncodingCase {{ id: {rust_str(page_id(source))}, "
            f"guesses: &[{', '.join(rust_str(g) for g in guesses)}], decoded_chars: {len(decoded)}, "
            f"decoded_blake2b: [{', '.join(f'0x{b:02x}' for b in digest)}] }},"
        )
    header("corpus", "tests/parity/encoding_cases.rs")
    print("// One row per corpus page that is not valid UTF-8: the ranked guesses of detect_encoding on the page")
    print("// bytes, and the length in chars and the blake2b-128 digest of the UTF-8 encoding of")
    print("// decode_file(page). The pages are third-party content, so the table holds digests, not text.")
    print()
    print("/// One non-UTF-8 corpus page and what upstream returns for it.")
    print("pub(crate) struct CorpusEncodingCase {")
    print("    pub(crate) id: &'static str,")
    print("    pub(crate) guesses: &'static [&'static str],")
    print("    pub(crate) decoded_chars: usize,")
    print("    pub(crate) decoded_blake2b: [u8; 16],")
    print("}")
    print()
    print("#[rustfmt::skip]")
    print("pub(crate) const CORPUS_ENCODING_CASES: &[CorpusEncodingCase] = &[")
    for row in rows:
        print(row)
    print("];")


if __name__ == "__main__":
    synthetic()
