"""Generates the files behind `crate::pyunicodedata`: Python's NFC tables and the cases that test them.

Regenerate with (from the repository root, Git Bash or Linux; Docker on Windows and macOS):

    scripts/oracle.sh 'from parity.gen_nfc import tables; tables()' > src/pyunicodedata/nfc.rs
    scripts/oracle.sh 'from parity.gen_nfc import cases; cases()' > src/pyunicodedata/cases.rs

Everything comes from the interpreter that runs this (`unicodedata` of Python 3.13, Unicode 15.1), so
the header records its version. The crate must not use a newer Unicode than Python does: NFC of a
character assigned after 15.1 stays as it is in Python.
"""

import sys
import unicodedata

from parity.gen_printable import ranges
from parity.gen_xpath_cases import rust_str

UNICODE_VERSION = "15.1.0"
MAX_CODE_POINT = 0x10FFFF
SURROGATES = range(0xD800, 0xE000)
HANGUL_SYLLABLES = range(0xAC00, 0xAC00 + 11172)
# Hangul vowel (V) and trailing consonant (T) jamo: they can only follow a leading consonant or a
# syllable, so NFC_QC is "maybe" for them. The algorithm composes them by arithmetic, not by table.
HANGUL_V = (0x1161, 0x1175)
HANGUL_T = (0x11A8, 0x11C2)
WIDTH = 100


def version() -> str:
    assert unicodedata.unidata_version == UNICODE_VERSION, unicodedata.unidata_version
    return f"Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}"


def nfc(text: str) -> str:
    return unicodedata.normalize("NFC", text)


def char_literal(code_point: int) -> str:
    assert code_point not in SURROGATES
    return f"'{chr(92)}u{{{code_point:X}}}'"


def hex_literal(value: int) -> str:
    return f"0x{value:X}"


def pack(cells: list[str]) -> str:
    """The cells, comma separated, as indented lines of at most `WIDTH` columns."""
    lines: list[str] = []
    line = "   "
    for cell in cells:
        if len(line) + 1 + len(cell) + 1 > WIDTH:
            lines.append(line)
            line = "   "
        line += f" {cell},"
    lines.append(line)
    return "\n".join(lines)


def header(path: str, call: str, summary: str) -> list[str]:
    return [
        f"// @generated by tools/parity/parity/gen_nfc.py with {version()}.",
        "// Do not edit. Regenerate from the repository root with:",
        f"//   scripts/oracle.sh 'from parity.gen_nfc import {call}; {call}()' > {path}",
        f"// {summary}",
        "",
    ]


def static(name: str, doc: str, element: str, cells: list[str]) -> str:
    return f"/// {doc}\n#[rustfmt::skip]\npub(super) static {name}: &[{element}] = &[\n{pack(cells)}\n];\n"


def decompositions() -> list[tuple[int, str]]:
    """Sorted (code point, full canonical decomposition), Hangul syllables left to arithmetic.

    `NFD` of one character is its recursive canonical mapping in canonical order; the crate sorts
    after decomposing, so the order here does not matter. The set must be exactly the characters whose
    `decomposition` field holds a mapping without a `<tag>`.
    """
    found = []
    for code_point in range(MAX_CODE_POINT + 1):
        if code_point in HANGUL_SYLLABLES:
            continue
        nfd = unicodedata.normalize("NFD", chr(code_point))
        if nfd != chr(code_point):
            found.append((code_point, nfd))
    mapped = [
        c
        for c in range(MAX_CODE_POINT + 1)
        if c not in HANGUL_SYLLABLES
        and unicodedata.decomposition(chr(c))
        and not unicodedata.decomposition(chr(c)).startswith("<")
    ]
    assert [c for c, _ in found] == mapped
    assert not any(ord(ch) in SURROGATES for _, nfd in found for ch in nfd)
    return found


def combining_classes() -> list[tuple[int, int, int]]:
    """Sorted inclusive (start, end, class) runs of the code points with a non-zero combining class."""
    runs: list[tuple[int, int, int]] = []
    for code_point in range(MAX_CODE_POINT + 1):
        cls = unicodedata.combining(chr(code_point))
        if not cls:
            continue
        if runs and runs[-1][1] == code_point - 1 and runs[-1][2] == cls:
            runs[-1] = (runs[-1][0], code_point, cls)
        else:
            runs.append((code_point, code_point, cls))
    return runs


def compositions(decomposed: list[tuple[int, str]]) -> list[tuple[int, int, int]]:
    """Sorted (first, second, composite): the inverse of the primary composites, without exclusions.

    A primary composite maps to exactly two characters; one that NFC does not rebuild from them is a
    composition exclusion and is left out, as are the singletons (one character).
    """
    pairs = []
    for composite, _ in decomposed:
        parts = [int(part, 16) for part in unicodedata.decomposition(chr(composite)).split()]
        if len(parts) != 2:
            assert len(parts) == 1, hex(composite)
            continue
        first, second = parts
        if nfc(chr(first) + chr(second)) == chr(composite):
            pairs.append((first, second, composite))
    pairs.sort()
    assert len({(first, second) for first, second, _ in pairs}) == len(pairs)
    return pairs


def tables() -> None:
    decomposed = decompositions()
    pairs = compositions(decomposed)
    no = ranges(lambda c: nfc(c) != c)
    seconds = {second for _, second, _ in pairs}
    maybe = ranges(lambda c: ord(c) in seconds or HANGUL_V[0] <= ord(c) <= HANGUL_V[1] or HANGUL_T[0] <= ord(c) <= HANGUL_T[1])
    out = header(
        "src/pyunicodedata/nfc.rs",
        "tables",
        "The Unicode data behind `unicodedata.normalize(\"NFC\", ...)`: decompositions, combining classes, composition pairs, quick check.",
    ) + [
        static(
            "DECOMPOSITIONS",
            "Full canonical decomposition of every character that has one (Hangul syllables excluded), sorted by character.",
            "(char, &str)",
            [f"({char_literal(c)}, {rust_str(d)})" for c, d in decomposed],
        ),
        static(
            "COMBINING_CLASSES",
            "Inclusive (start, end, canonical combining class) runs of the characters whose class is not 0, sorted.",
            "(u32, u32, u8)",
            [f"({hex_literal(s)}, {hex_literal(e)}, {cls})" for s, e, cls in combining_classes()],
        ),
        static(
            "COMPOSITIONS",
            "(first, second, composite): the primary composites NFC builds, sorted by (first, second). Hangul by arithmetic.",
            "(char, char, char)",
            [f"({char_literal(a)}, {char_literal(b)}, {char_literal(c)})" for a, b, c in pairs],
        ),
        static(
            "NFC_NO",
            "Inclusive ranges of the characters whose NFC form is not themselves (NFC_QC no).",
            "(u32, u32)",
            [f"({hex_literal(s)}, {hex_literal(e)})" for s, e in no],
        ),
        static(
            "NFC_MAYBE",
            "Inclusive ranges of the characters that can end a composite pair, Hangul V and T jamo included (NFC_QC maybe).",
            "(u32, u32)",
            [f"({hex_literal(s)}, {hex_literal(e)})" for s, e in maybe],
        ),
    ]
    sys.stdout.write("\n".join(out))


def cases() -> None:
    decomposed = decompositions()
    pairs = compositions(decomposed)
    interesting = sorted({c for c, _ in decomposed} | {c for s, e, _ in combining_classes() for c in range(s, e + 1)})
    after = chr(0x301)
    rows = [
        f"({char_literal(c)}, {rust_str(nfc(chr(c)))}, {rust_str(nfc('a' + chr(c) + after))})"
        for c in interesting
    ]
    pair_rows = [f"({char_literal(a)}, {char_literal(b)}, {rust_str(nfc(chr(a) + chr(b)))})" for a, b, _ in pairs]
    hangul = [chr(0x1100) + chr(0x1161), chr(0x1100) + chr(0x1161) + chr(0x11A8)]
    hangul_rows = [f"({rust_str(text)}, {rust_str(nfc(text))})" for text in hangul]
    out = header(
        "src/pyunicodedata/cases.rs",
        "cases",
        "Python's `unicodedata.normalize(\"NFC\", ...)` on fixed inputs.",
    ) + [
        "/// A character, NFC of it alone, and NFC of `a`, the character and U+0301; one row for every character with a",
        "/// decomposition or a non-zero combining class.",
        "#[rustfmt::skip]\npub(super) static CHARACTER_CASES: &[(char, &str, &str)] = &[",
        pack(rows),
        "];",
        "",
        "/// The two characters of every composition pair and NFC of them joined.",
        "#[rustfmt::skip]\npub(super) static PAIR_CASES: &[(char, char, &str)] = &[",
        pack(pair_rows),
        "];",
        "",
        "/// Input and NFC of Hangul jamo sequences, which compose by arithmetic: L+V and L+V+T.",
        "#[rustfmt::skip]\npub(super) static HANGUL_CASES: &[(&str, &str)] = &[",
        pack(hangul_rows),
        "];",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    tables()
